<?php
namespace App\Jobs;

use App\Models\{Memory,Message};
use Dompdf\Dompdf;
use Dompdf\Options;
use Illuminate\Bus\Queueable;
use Illuminate\Contracts\Queue\ShouldQueue;
use Illuminate\Queue\InteractsWithQueue;
use Illuminate\Queue\SerializesModels;
use Illuminate\Support\Facades\{DB,Storage};

class GenerateDataExport implements ShouldQueue
{
    use InteractsWithQueue, Queueable, SerializesModels;

    public int $tries = 3;

    public function __construct(
        public string $exportId,
        public string $userId,
        public ?string $coupleSpaceId,
        public string $format
    ) {}

    public function handle(): void
    {
        DB::table('data_exports')->where('id', $this->exportId)->update([
            'status' => 'processing',
            'updated_at' => now(),
        ]);

        $payload = [
            'generated_at' => now()->toIso8601String(),
            'user' => DB::table('users')->where('id', $this->userId)->first([
                'id', 'username', 'display_name', 'bio', 'timezone', 'locale', 'created_at',
            ]),
            'couple_space' => $this->coupleSpaceId
                ? DB::table('couple_spaces')->where('id', $this->coupleSpaceId)->first()
                : null,
            'memories' => $this->coupleSpaceId
                ? Memory::where('couple_space_id', $this->coupleSpaceId)->get()
                : [],
            'messages' => $this->coupleSpaceId
                ? Message::where('couple_space_id', $this->coupleSpaceId)->get()
                : [],
            'calendar_events' => $this->coupleSpaceId
                ? DB::table('calendar_events')->where('couple_space_id', $this->coupleSpaceId)->whereNull('deleted_at')->get()
                : [],
            'goals' => $this->coupleSpaceId
                ? DB::table('goals')->where('couple_space_id', $this->coupleSpaceId)->whereNull('deleted_at')->get()
                : [],
        ];

        if (strtolower($this->format) === 'pdf') {
            $options = new Options();
            $options->set('isRemoteEnabled', false);
            $options->set('isPhpEnabled', false);
            $dompdf = new Dompdf($options);
            $dompdf->setPaper('A4');
            $dompdf->loadHtml($this->renderHtml($payload), 'UTF-8');
            $dompdf->render();
            $body = $dompdf->output();
            $ext = 'pdf';
            $contentType = 'application/pdf';
        } else {
            $body = json_encode($payload, JSON_PRETTY_PRINT | JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES);
            $ext = 'json';
            $contentType = 'application/json';
        }

        $key = 'exports/'.$this->userId.'/'.$this->exportId.'.'.$ext;
        Storage::disk(config('143.upload_disk'))->put($key, $body, [
            'visibility' => 'private',
            'ContentType' => $contentType,
        ]);

        DB::table('data_exports')->where('id', $this->exportId)->update([
            'status' => 'completed',
            'data' => json_encode([
                'storage_key' => $key,
                'requested_format' => strtolower($this->format),
                'actual_format' => $ext,
                'content_type' => $contentType,
            ]),
            'completed_at' => now(),
            'updated_at' => now(),
        ]);
    }

    private function renderHtml(array $payload): string
    {
        $json = htmlspecialchars(
            json_encode($payload, JSON_PRETTY_PRINT | JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES),
            ENT_QUOTES | ENT_SUBSTITUTE,
            'UTF-8'
        );

        return <<<HTML
<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<title>143 Data Export</title>
<style>
body{font-family:DejaVu Sans,sans-serif;font-size:10px;color:#222;margin:28px}
h1{font-size:20px;margin:0 0 6px}p{margin:0 0 14px;color:#555}pre{white-space:pre-wrap;word-wrap:break-word;line-height:1.35}
</style>
</head>
<body>
<h1>143 Data Export</h1>
<p>Private user/couple data export generated by 143.</p>
<pre>{$json}</pre>
</body>
</html>
HTML;
    }
}
